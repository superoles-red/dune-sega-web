#!/usr/bin/env python3
"""Extract lossless native shop UI parts; standard library only.

Run after extract_shop_ui.c. PNGs are exact native-resolution crops or native
indexed sprite decoding. No RGB colour-keying, repainting, scaling, or AI art.
"""
from pathlib import Path
import argparse, hashlib, json, struct, zlib

ROOT=Path(__file__).resolve().parents[1]

def png(path,w,h,pixels,channels=3):
    def chunk(kind,data):
        return struct.pack('>I',len(data))+kind+data+struct.pack('>I',zlib.crc32(kind+data)&0xffffffff)
    stride=w*channels
    data=b''.join(b'\0'+pixels[y*stride:(y+1)*stride] for y in range(h))
    Path(path).parent.mkdir(parents=True,exist_ok=True)
    Path(path).write_bytes(b'\x89PNG\r\n\x1a\n'+chunk(b'IHDR',struct.pack('>IIBBBBB',w,h,8,6 if channels==4 else 2,0,0,0))+chunk(b'IDAT',zlib.compress(data,9))+chunk(b'IEND',b''))

def crop(rgb,rect,channels=3):
    x,y,w,h=rect
    assert x>=0 and y>=0 and x+w<=320 and y+h<=224
    return b''.join(rgb[((y+yy)*320+x)*channels:((y+yy)*320+x+w)*channels] for yy in range(h))

